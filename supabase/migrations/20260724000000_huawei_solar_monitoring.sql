CREATE OR REPLACE FUNCTION public.solar_claim_sync_job(p_worker text)
RETURNS SETOF public.huawei_sync_jobs
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  RETURN QUERY
  WITH next_job AS (
    SELECT id FROM public.huawei_sync_jobs
    WHERE status IN ('pending', 'retrying') AND scheduled_at <= now()
    ORDER BY priority ASC, scheduled_at ASC
    FOR UPDATE SKIP LOCKED
    LIMIT 1
  )
  UPDATE public.huawei_sync_jobs j
  SET status = 'running', claimed_at = now(), claimed_by = p_worker,
      started_at = now(), attempts = attempts + 1, updated_at = now()
  FROM next_job
  WHERE j.id = next_job.id
  RETURNING j.*;
END;
$$;

CREATE OR REPLACE FUNCTION public.solar_lock_huawei_login(p_integration_id uuid, p_owner text)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE v_locked boolean;
BEGIN
  UPDATE huawei_integrations
  SET session_lock_owner = p_owner, session_lock_until = now() + interval '45 seconds'
  WHERE id = p_integration_id
    AND (session_lock_until IS NULL OR session_lock_until < now() OR session_lock_owner = p_owner)
  RETURNING true INTO v_locked;
  RETURN COALESCE(v_locked, false);
END;
$$;

