CREATE OR REPLACE FUNCTION public.solar_has_access()
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM public.users
    WHERE auth_user_id = auth.uid()
      AND role IN ('super_admin', 'manager_sale', 'manager_marketing', 'engineer')
  );
$$;

