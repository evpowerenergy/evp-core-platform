CREATE OR REPLACE FUNCTION public.solar_get_alarm_summary(p_filters jsonb DEFAULT '{}'::jsonb)
RETURNS jsonb
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  WITH filtered AS (
    SELECT a.*, p.plant_name, d.device_name
    FROM huawei_alarm_events a
    LEFT JOIN huawei_plants p ON p.id = a.plant_id
    LEFT JOIN huawei_devices d ON d.id = a.device_id
    WHERE solar_has_access()
      AND (p_filters->>'status' IS NULL OR a.status = p_filters->>'status')
      AND (p_filters->>'severity' IS NULL OR a.severity = (p_filters->>'severity')::integer)
  )
  SELECT jsonb_build_object(
    'activeCount', (SELECT count(*) FROM filtered WHERE status = 'active'),
    'bySeverity', COALESCE((SELECT jsonb_object_agg(severity, count) FROM (SELECT severity, count(*) count FROM filtered WHERE status='active' GROUP BY severity) x), '{}'::jsonb),
    'items', COALESCE((SELECT jsonb_agg(to_jsonb(f) - 'raw_payload' ORDER BY raised_at DESC) FROM (SELECT * FROM filtered LIMIT 500) f), '[]'::jsonb)
  );
$$;

CREATE OR REPLACE FUNCTION public.solar_get_data_health(p_from timestamptz DEFAULT now() - interval '24 hours')
RETURNS jsonb
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT CASE WHEN NOT solar_has_access() THEN NULL ELSE jsonb_build_object(
    'lastSuccessfulSync', (SELECT max(finished_at) FROM huawei_sync_runs WHERE status = 'success'),
    'failedRuns', (SELECT count(*) FROM huawei_sync_runs WHERE started_at >= p_from AND status IN ('failed','dead_letter')),
    'rateLimitIncidents', (SELECT count(*) FROM huawei_sync_runs WHERE started_at >= p_from AND fail_code IN ('407','429')),
    'queueBacklog', (SELECT count(*) FROM huawei_sync_jobs WHERE status IN ('pending','retrying')),
    'deadLetterCount', (SELECT count(*) FROM huawei_sync_jobs WHERE status = 'dead_letter'),
    'stalePlants', (SELECT count(*) FROM huawei_plants p WHERE visible_in_dashboard AND (last_synced_at IS NULL OR last_synced_at < now() - interval '15 minutes')),
    'openQualityIssues', (SELECT count(*) FROM huawei_data_quality_issues WHERE resolved_at IS NULL),
    'qualityByType', COALESCE((SELECT jsonb_object_agg(issue_type, count) FROM (
      SELECT issue_type, count(*) count FROM huawei_data_quality_issues WHERE resolved_at IS NULL GROUP BY issue_type
    ) q), '{}'::jsonb),
    'recentRuns', COALESCE((SELECT jsonb_agg(to_jsonb(r) ORDER BY started_at DESC) FROM (SELECT * FROM huawei_sync_runs ORDER BY started_at DESC LIMIT 100) r), '[]'::jsonb)
  ) END;
$$;

CREATE OR REPLACE FUNCTION public.solar_get_customer_mapping_candidates(p_plant_id uuid)
RETURNS jsonb
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT CASE WHEN NOT solar_is_admin() THEN '[]'::jsonb ELSE COALESCE(jsonb_agg(to_jsonb(x)), '[]'::jsonb) END
  FROM (
    SELECT cs.id, cs.customer_group, cs.province, cs.district, cs.capacity_kw,
      (
        CASE WHEN lower(cs.customer_group) = lower(p.plant_name) THEN 50 ELSE 0 END +
        CASE WHEN cs.province = p.province THEN 25 ELSE 0 END +
        CASE WHEN cs.capacity_kw IS NOT NULL AND p.capacity_kwp IS NOT NULL
          AND abs(cs.capacity_kw - p.capacity_kwp) <= greatest(1, p.capacity_kwp * 0.1) THEN 25 ELSE 0 END
      ) AS match_score
    FROM huawei_plants p CROSS JOIN customer_services cs
    LEFT JOIN huawei_plant_customer_links l ON l.customer_service_id = cs.id
    WHERE p.id = p_plant_id AND l.customer_service_id IS NULL
    ORDER BY match_score DESC, cs.customer_group
    LIMIT 20
  ) x;
$$;

CREATE OR REPLACE FUNCTION public.solar_confirm_customer_mapping(p_plant_id uuid, p_customer_service_id integer)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF NOT solar_is_admin() THEN RAISE EXCEPTION 'Forbidden'; END IF;
  INSERT INTO huawei_plant_customer_links (plant_id, customer_service_id, match_status, confirmed_by, confirmed_at)
  VALUES (p_plant_id, p_customer_service_id, 'confirmed', auth.uid(), now())
  ON CONFLICT (plant_id) DO UPDATE SET customer_service_id = excluded.customer_service_id,
    match_status = 'confirmed', confirmed_by = auth.uid(), confirmed_at = now(), updated_at = now();
  RETURN true;
END;
$$;

CREATE OR REPLACE FUNCTION public.solar_set_tariff(
  p_plant_id uuid, p_name text, p_import_rate numeric, p_export_rate numeric,
  p_valid_from date, p_valid_to date DEFAULT NULL
) RETURNS uuid
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE v_id uuid;
BEGIN
  IF NOT solar_is_admin() THEN RAISE EXCEPTION 'Forbidden'; END IF;
  INSERT INTO huawei_tariffs (
    plant_id, name, import_rate_per_kwh, export_rate_per_kwh, valid_from, valid_to,
    confirmed_by, confirmed_at
  ) VALUES (
    p_plant_id, p_name, p_import_rate, p_export_rate, p_valid_from, p_valid_to,
    auth.uid(), now()
  )
  ON CONFLICT (plant_id, valid_from) DO UPDATE SET
    name = excluded.name, import_rate_per_kwh = excluded.import_rate_per_kwh,
    export_rate_per_kwh = excluded.export_rate_per_kwh, valid_to = excluded.valid_to,
    confirmed_by = auth.uid(), confirmed_at = now(), updated_at = now()
  RETURNING id INTO v_id;
  RETURN v_id;
END;
$$;

