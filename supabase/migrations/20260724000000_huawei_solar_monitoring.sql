CREATE OR REPLACE FUNCTION public.solar_refresh_data_quality(p_integration_id uuid)
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE v_count integer;
BEGIN
  INSERT INTO huawei_data_quality_issues (
    integration_id, plant_id, issue_key, issue_type, severity, details, last_seen_at, resolved_at
  )
  SELECT p_integration_id, p.id, 'stale_plant:' || p.id, 'stale_plant',
    CASE WHEN max(s.sampled_at) < now() - interval '1 hour' OR max(s.sampled_at) IS NULL THEN 'critical' ELSE 'warning' END,
    jsonb_build_object('latestSampleAt', max(s.sampled_at), 'thresholdMinutes', 15),
    now(), NULL
  FROM huawei_plants p
  LEFT JOIN huawei_plant_samples s ON s.plant_id = p.id
  WHERE p.integration_id = p_integration_id AND p.enabled_for_sync
  GROUP BY p.id
  HAVING max(s.sampled_at) IS NULL OR max(s.sampled_at) < now() - interval '15 minutes'
  ON CONFLICT (integration_id, issue_key) DO UPDATE SET
    severity = excluded.severity, details = excluded.details, last_seen_at = now(), resolved_at = NULL;

  INSERT INTO huawei_data_quality_issues (
    integration_id, plant_id, issue_key, issue_type, severity, details, last_seen_at, resolved_at
  )
  SELECT p_integration_id, p.id, 'missing_intervals:' || p.id, 'missing_intervals', 'warning',
    jsonb_build_object('sampleCount24h', count(s.id), 'expectedApprox', 288),
    now(), NULL
  FROM huawei_plants p
  LEFT JOIN huawei_plant_samples s ON s.plant_id = p.id AND s.sampled_at >= now() - interval '24 hours'
  WHERE p.integration_id = p_integration_id AND p.enabled_for_sync
  GROUP BY p.id
  HAVING count(s.id) < 259
  ON CONFLICT (integration_id, issue_key) DO UPDATE SET
    details = excluded.details, last_seen_at = now(), resolved_at = NULL;

  UPDATE huawei_data_quality_issues q
  SET resolved_at = now()
  WHERE integration_id = p_integration_id AND resolved_at IS NULL
    AND (
      (issue_type = 'stale_plant' AND EXISTS (
        SELECT 1 FROM huawei_plant_samples s WHERE s.plant_id = q.plant_id
          AND s.sampled_at >= now() - interval '15 minutes'
      ))
      OR
      (issue_type = 'missing_intervals' AND (
        SELECT count(*) FROM huawei_plant_samples s WHERE s.plant_id = q.plant_id
          AND s.sampled_at >= now() - interval '24 hours'
      ) >= 259)
    );

  DELETE FROM huawei_sync_runs WHERE started_at < now() - interval '180 days';
  DELETE FROM huawei_plant_samples WHERE sampled_at < now() - interval '24 months';
  DELETE FROM huawei_device_samples WHERE sampled_at < now() - interval '24 months';
  SELECT count(*) INTO v_count FROM huawei_data_quality_issues
    WHERE integration_id = p_integration_id AND resolved_at IS NULL;
  RETURN v_count;
END;
$$;

CREATE OR REPLACE FUNCTION public.solar_get_fleet_summary(p_filters jsonb DEFAULT '{}'::jsonb)
RETURNS jsonb
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  WITH allowed AS (
    SELECT p.* FROM huawei_plants p
    WHERE solar_has_access() AND p.visible_in_dashboard
      AND (p_filters->>'province' IS NULL OR p.province = p_filters->>'province')
  ), latest AS (
    SELECT DISTINCT ON (s.plant_id) s.*
    FROM huawei_plant_samples s JOIN allowed p ON p.id = s.plant_id
    ORDER BY s.plant_id, s.sampled_at DESC
  ), active_alarm AS (
    SELECT count(*) count FROM huawei_alarm_events a
    JOIN allowed p ON p.id = a.plant_id WHERE a.status = 'active'
  )
  SELECT jsonb_build_object(
    'plantCount', (SELECT count(*) FROM allowed),
    'capacityKwp', COALESCE((SELECT sum(capacity_kwp) FROM allowed), 0),
    'currentPowerKw', COALESCE((SELECT sum(current_power_kw) FROM latest), 0),
    'dailyEnergyKwh', COALESCE((SELECT sum(daily_energy_kwh) FROM latest), 0),
    'healthyCount', (SELECT count(*) FROM latest WHERE health_state = 3),
    'faultyCount', (SELECT count(*) FROM latest WHERE health_state = 2),
    'offlineCount', (SELECT count(*) FROM latest WHERE health_state = 1),
    'activeAlarmCount', (SELECT count FROM active_alarm),
    'latestSampleAt', (SELECT max(sampled_at) FROM latest)
  );
$$;

CREATE OR REPLACE FUNCTION public.solar_get_plant_list(
  p_filters jsonb DEFAULT '{}'::jsonb,
  p_sort text DEFAULT 'name_asc',
  p_page integer DEFAULT 1,
  p_page_size integer DEFAULT 25
) RETURNS jsonb
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  WITH filtered AS (
    SELECT p.*, l.customer_service_id,
      s.sampled_at, s.current_power_kw, s.daily_energy_kwh, s.health_state AS latest_health_state
    FROM huawei_plants p
    LEFT JOIN huawei_plant_customer_links l ON l.plant_id = p.id
    LEFT JOIN LATERAL (
      SELECT * FROM huawei_plant_samples ps WHERE ps.plant_id = p.id ORDER BY sampled_at DESC LIMIT 1
    ) s ON true
    WHERE solar_has_access() AND p.visible_in_dashboard
      AND (
        COALESCE(p_filters->>'search', '') = ''
        OR p.plant_name ILIKE ('%' || (p_filters->>'search') || '%')
        OR p.plant_code ILIKE ('%' || (p_filters->>'search') || '%')
      )
      AND (p_filters->>'province' IS NULL OR p.province = p_filters->>'province')
      AND (p_filters->>'healthState' IS NULL OR s.health_state = (p_filters->>'healthState')::integer)
  ), ordered AS (
    SELECT * FROM filtered
    ORDER BY
      CASE WHEN p_sort = 'power_desc' THEN current_power_kw END DESC NULLS LAST,
      CASE WHEN p_sort = 'energy_desc' THEN daily_energy_kwh END DESC NULLS LAST,
      CASE WHEN p_sort = 'name_desc' THEN plant_name END DESC,
      plant_name ASC
    LIMIT LEAST(GREATEST(p_page_size, 1), 100)
    OFFSET (GREATEST(p_page, 1) - 1) * LEAST(GREATEST(p_page_size, 1), 100)
  )
  SELECT jsonb_build_object(
    'items', COALESCE((SELECT jsonb_agg(to_jsonb(o) - 'raw_payload') FROM ordered o), '[]'::jsonb),
    'total', (SELECT count(*) FROM filtered),
    'page', GREATEST(p_page, 1),
    'pageSize', LEAST(GREATEST(p_page_size, 1), 100)
  );
$$;

